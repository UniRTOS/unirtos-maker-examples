const tag_glyph_t *tag_font_find(uint32_t codepoint, unsigned int size)
{
    size_t first = 0u;
    size_t last = sizeof(tag_glyphs) / sizeof(tag_glyphs[0]);

    while (first < last) {
        size_t middle = first + (last - first) / 2u;
        const tag_glyph_t *glyph = &tag_glyphs[middle];

        if (glyph->size < size || (glyph->size == size && glyph->codepoint < codepoint)) {
            first = middle + 1u;
        } else {
            last = middle;
        }
    }

    if (first < sizeof(tag_glyphs) / sizeof(tag_glyphs[0]) &&
        tag_glyphs[first].size == size && tag_glyphs[first].codepoint == codepoint) {
        return &tag_glyphs[first];
    }
    return NULL;
}
